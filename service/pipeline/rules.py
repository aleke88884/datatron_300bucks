def expand_clause(clause: str) -> list[str]:
    """«п. 16 пп. 3), пп. 4)» → ['п. 16 пп. 3)', 'п. 16 пп. 4)']; «п. 20 абз. 2» и «п. 71 пп. 9)» — один ключ."""
    out: list[str] = []
    base = None
    for p in (x.strip() for x in clause.split(",")):
        m = re.match(r"^(п\. [\d–-]+)", p)
        if m:
            base = m.group(1)
            out.append(p)
        else:
            if not (base and p.startswith("пп.")):
                raise ValueError(f"не разобран пункт: {p!r}")
            out.append(f"{base} {p}")
    return out


